// События между сервисами. Лежат в contracts, потому что у события два конца:
// издатель в ingestor и потребитель в api, и разойтись они не должны молча.
//
// Версия в имени топика, а не в поле: v2 поедет рядом с v1, пока потребители
// переключаются. Переименование топика — единственный способ сломать
// совместимость заметно.
export const PRICES_TOPIC = 'market.prices.v1'

// Ключ сообщения — тикер. Порядок Kafka гарантирует только внутри партиции, а
// партицию выбирает ключ: без него две цены одной бумаги разъедутся по
// разным партициям и могут прийти задом наперёд.
export type PriceQuoted = {
  // Идентификатор из общего справочника: потребителю не нужно искать бумагу
  // по тикеру, он кладёт цену сразу.
  instrumentId: string
  symbol: string
  source: string
  // Строкой: деньги не бывают number, в том числе в JSON.
  price: string
  // ISO UTC, время биржи — не время получения.
  quotedAt: string
}
