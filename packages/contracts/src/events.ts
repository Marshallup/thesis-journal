import type { RawOperation } from './operations.ts'

// События между сервисами. Лежат в contracts, потому что у события два конца:
// издатель в ingestor и потребитель в api, и разойтись они не должны молча.
//
// Версия в имени топика, а не в поле: v2 поедет рядом с v1, пока потребители
// переключаются. Переименование топика — единственный способ сломать
// совместимость заметно.
export const PRICES_TOPIC = 'market.prices.v1'

// Ключ сообщения — тикер. Порядок Kafka гарантирует только внутри партиции, а
// партицию выбирает ключ: без него две цены одной бумаги разъедутся по
// разным партициям и могут прийти задом наперёд.
export type PriceQuoted = {
  // Идентификатор из общего справочника: потребителю не нужно искать бумагу
  // по тикеру, он кладёт цену сразу.
  instrumentId: string
  symbol: string
  source: string
  // Строкой: деньги не бывают number, в том числе в JSON.
  price: string
  // ISO UTC, время биржи — не время получения.
  quotedAt: string
}

// Команда: «разбери этот отчёт». RabbitMQ, потому что это задание одному
// исполнителю, а не факт для всех желающих.
export const IMPORT_PARSE_QUEUE = 'import.parse'

export type ImportParse = {
  importId: string
  accountId: string
  // Владелец данных. Едет сквозь всю цепочку потому, что применять операции
  // придётся под RLS, а у консьюмера нет сессии и спросить пользователя
  // неоткуда. Альтернатива — роль, обходящая RLS, — хуже: она сняла бы второй
  // рубеж защиты со всего пути применения.
  userId: string
  source: string
  // sha256 содержимого: воркер кладёт его рядом с байтами, чтобы сырьё можно
  // было опознать, не спрашивая api.
  fileHash: string
  // Байты отчёта в base64 — при первой отправке. При повторном разборе их нет:
  // сырьё уже лежит у воркера, и гонять файл второй раз незачем.
  payloadBase64?: string
}

// Событие: «отчёт разобран». Kafka, потому что это факт, и потребителей у него
// со временем станет больше одного.
export const IMPORT_PARSED_TOPIC = 'import.parsed.v1'

export type ImportParsed = {
  importId: string
  accountId: string
  userId: string
  source: string
  // Пусто и error заполнен — разбор отказал. Отдельного топика под отказ нет:
  // потребитель один и тот же, и ему важно не «что случилось», а «что теперь
  // с этим импортом».
  operations: RawOperation[]
  error?: string
}

// Команда «сохрани ключ от биржи». Секрет едет шифротекстом: сообщения
// RabbitMQ лежат на диске и попадают в дампы, а мастер-ключ — файлом на
// сервере, и в брокер не попадает никогда.
export const EXCHANGE_KEY_SAVE_QUEUE = 'exchange-key.save'

export type ExchangeKeySave = {
  accountId: string
  exchange: 'bybit'
  // Публичная часть ключа секретом не является: по ней биржа опознаёт запрос,
  // а человек — свой ключ в списке.
  apiKeyPublic: string
  ciphertextBase64: string
  nonceBase64: string
  tagBase64: string
}
