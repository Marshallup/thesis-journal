-- Имя счёта. Необязательное: счёт часто заводят по ходу записи сделки, и
-- требовать там название значит мешать. Уже заведённые счета остаются
-- безымянными, интерфейс подписывает их провайдером, валютой и датой.
alter table "accounts" add column "name" TEXT;

-- Два счёта с одним именем у одного человека — опечатка, а не выбор: имя
-- заводится ровно ради того, чтобы различать. NULL-ы в уникальном индексе
-- различны, поэтому безымянных счетов может быть сколько угодно.
create unique index "account_name_unique" on "accounts"("user_id", "name");
