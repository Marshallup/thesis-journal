-- Итог применения рядом со статусом. Раньше «создано N, пропущено M» возвращал
-- тот же запрос, что применял отчёт: экран спрашивал и сразу получал ответ.
-- Теперь применение происходит по событию, и ответа на запрос нет — значит
-- итог надо сохранить, иначе человек видит «готово» без единой цифры.
--
-- jsonb, а не три колонки: состав итога ещё будет меняться (отложенные,
-- комиссии, дивиденды), и каждая правка не должна быть миграцией.
alter table "imports" add column "result" JSONB;
