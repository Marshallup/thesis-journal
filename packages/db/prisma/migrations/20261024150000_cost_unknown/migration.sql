-- Пометка «себестоимость неизвестна».
--
-- Монета попадает на биржу не только покупкой: депозит с другого кошелька,
-- airdrop, перевод, P2P. Цены покупки у такого прихода нет вовсе, а FIFO без
-- себестоимости считать нечего — и до сих пор такая продажа висела отложенной
-- навсегда.
--
-- Решено 24.10.2026: приход записывается лотом с нулевой себестоимостью и этой
-- пометкой. Продажа применится, но прибыль по ней будет завышена на всю
-- стоимость монеты — поэтому пометка, а не молчание: завышение должно быть
-- видно на экране.
ALTER TABLE public.trades ADD COLUMN cost_unknown boolean DEFAULT false NOT NULL;
