-- Права воркера, которые раньше выдавал только скрипт ролей.
--
-- Почему это сломалось. `docker/postgres/init-app-role.sh` выдаёт роли воркера
-- `usage` на схему `ingestor` и `select` на `public.instruments` — но оба
-- гранта стоят под условием «объект существует», потому что на свежем кластере
-- скрипт выполняется из initdb.d, то есть **до** миграций. Безусловный грант
-- там once уже ронял инициализацию контейнера целиком.
--
-- Получалось так: пересоздали том → скрипт пропустил оба гранта → миграции
-- создали схему и справочник, но прав не выдали → воркер поднялся и упёрся в
-- «permission denied for schema ingestor». Лечилось повторным `pnpm db:role`,
-- про который надо помнить, а значит однажды не вспомнить.
--
-- Теперь права выдаёт миграция: к этому моменту и схема, и справочник уже
-- существуют, порядок гарантирован. Скрипт ролей остаётся для того, для чего он
-- и нужен — создать роли и их пароли.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'thesis_ingestor') then
    execute $g$GRANT USAGE ON SCHEMA ingestor TO thesis_ingestor$g$;
    -- Единственное исключение из «только своя схема»: без справочника воркер
    -- не знает, какие бумаги опрашивать. Только select и только эта таблица.
    execute $g$GRANT SELECT ON TABLE public.instruments TO thesis_ingestor$g$;
  end if;
end
$$;
