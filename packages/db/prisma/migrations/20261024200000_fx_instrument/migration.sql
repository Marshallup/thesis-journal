-- Курс доллара как инструмент справочника.
--
-- Курс — такая же котировка, как цена бумаги: у неё есть источник, время и
-- значение, и меняется она так же. Поэтому отдельной таблицы под курсы нет:
-- `USDRUB` живёт в справочнике инструментов классом `currency`, а его значения
-- идут тем же путём, что цены MOEX и Bybit — воркер пишет, outbox публикует,
-- `api` проецирует.
--
-- Строка заводится миграцией, а не воркером: справочник живёт в схеме api, и
-- прав на запись в него у роли воркера нет. Это та же граница между сервисами,
-- ради которой заведены отдельные схемы.
INSERT INTO public.instruments (symbol, class, currency)
VALUES ('USDRUB', 'currency', 'RUB')
ON CONFLICT (symbol, class) DO NOTHING;
