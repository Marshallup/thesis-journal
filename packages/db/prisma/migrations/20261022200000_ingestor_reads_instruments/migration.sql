-- Право воркера на справочник выдаётся миграцией, а не только скриптом ролей.
-- Причина: на свежем кластере скрипт выполняется из initdb.d, то есть раньше
-- миграций, и справочника в тот момент нет — там грант пропускается. Если бы
-- он остался только в скрипте, его пришлось бы помнить и прогонять вручную
-- после каждой инициализации, а забытый грант даёт воркера, который молча не
-- знает ни одной бумаги.
--
-- Роль создаёт тот же скрипт, и на свежем кластере он уже выполнился. Условие
-- на всякий случай: миграции применяют и на базу, поднятую иначе.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'thesis_ingestor') then
    grant select on table public.instruments to thesis_ingestor;
  end if;
end
$$;
